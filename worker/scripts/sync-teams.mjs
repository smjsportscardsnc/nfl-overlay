// Copies the team lists from ../js/leagues.js into src/teams.js so the worker
// matches Whatnot titles against exactly the teams the board shows.
// Run after changing js/leagues.js:  npm run sync-teams
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const ctx = { window: {} };
vm.runInNewContext(readFileSync(here("../../js/leagues.js"), "utf8"), ctx);
const out = {};
for (const [key, league] of Object.entries(ctx.window.SMJ_LEAGUES)) {
  out[key] = league.teams.map(({ abbr, city, name }) => ({ abbr, city, name }));
}
writeFileSync(
  here("../src/teams.js"),
  "// Generated by scripts/sync-teams.mjs from js/leagues.js. Do not edit by hand.\n" +
    "export const LEAGUES = " + JSON.stringify(out, null, 0).replace(/\},\{/g, "},\n  {") + ";\n"
);
console.log("Wrote src/teams.js:", Object.entries(out).map(([k, t]) => `${k} ${t.length}`).join(", "));
